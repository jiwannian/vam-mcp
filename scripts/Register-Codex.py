"""Register only this MCP entry, preserving all unrelated Codex settings."""
from pathlib import Path
import copy
import argparse
import json
import os
import re
import shutil
import sys
import time
import uuid

try:
    import tomllib
except ImportError:
    import tomli as tomllib


def without_vam_tables(text: str):
    pattern = r"(?ms)^\[mcp_servers\.vam(?:\.[A-Za-z0-9_-]+)*\][ \t]*(?:#[^\n]*)?\r?\n.*?(?=^\[|\Z)"
    return re.sub(pattern, "", text).rstrip()


def unregistered_config(text: str):
    expected = tomllib.loads(text)
    expected.get("mcp_servers", {}).pop("vam", None)
    updated = without_vam_tables(text) + "\n"
    actual = tomllib.loads(updated)
    for data in (expected, actual):
        if data.get("mcp_servers") == {}:
            data.pop("mcp_servers")
    if actual != expected:
        raise ValueError("Removal would change unrelated Codex settings")
    return updated


def updated_config(text: str, project: Path, python: str, game_root: str = ""):
    parsed = tomllib.loads(text)
    entry = {
        "startup_timeout_sec": 20,
        "tool_timeout_sec": 240,
        "command": python,
        "args": [str(project / "server.py")],
        "env": {"PYTHONIOENCODING": "utf-8", "PYTHONUTF8": "1", **({"VAM_GAME_ROOT": game_root} if game_root else {})},
    }
    expected = copy.deepcopy(parsed)
    expected.setdefault("mcp_servers", {})["vam"] = entry
    # Only the dedicated tables generated by this installer are replaced.
    preserved = without_vam_tables(text)
    quote = lambda value: json.dumps(value, ensure_ascii=False)
    section = (
        "[mcp_servers.vam]\n"
        "startup_timeout_sec = 20\n"
        "tool_timeout_sec = 240\n"
        f"command = {quote(python)}\n"
        f"args = [{quote(str(project / 'server.py'))}]\n\n"
        "[mcp_servers.vam.env]\n"
        'PYTHONIOENCODING = "utf-8"\n'
        'PYTHONUTF8 = "1"\n'
        + (f"VAM_GAME_ROOT = {quote(game_root)}\n" if game_root else "")
    )
    updated = (preserved + "\n\n" if preserved else "") + section
    if tomllib.loads(updated) != expected:
        raise ValueError("Registration would change unrelated Codex settings")
    return updated


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--remove", action="store_true")
    parser.add_argument("--game-root", default=os.environ.get("VAM_GAME_ROOT", ""))
    options = parser.parse_args()
    project = Path(__file__).resolve().parent.parent
    config = Path(os.environ["USERPROFILE"]) / ".codex/config.toml"
    text = config.read_text(encoding="utf-8-sig") if config.exists() else ""
    updated = unregistered_config(text) if options.remove else updated_config(text, project, sys.executable, str(Path(options.game_root).resolve()) if options.game_root else "")
    if text == updated:
        print("VaM MCP registration is current.")
        return
    if config.exists():
        backup = project / "runtime/backups" / ("codex-config-" + time.strftime("%Y%m%d-%H%M%S") + "-" + uuid.uuid4().hex[:8] + ".toml")
        backup.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(config, backup)
    config.parent.mkdir(parents=True, exist_ok=True)
    temporary = config.with_name("config.vam." + uuid.uuid4().hex + ".tmp")
    temporary.write_text(updated, encoding="utf-8")
    os.replace(temporary, config)
    print("VaM MCP registration removed." if options.remove else "VaM MCP registered. Restart Codex's MCP connection to load its tools.")


if __name__ == "__main__":
    main()
